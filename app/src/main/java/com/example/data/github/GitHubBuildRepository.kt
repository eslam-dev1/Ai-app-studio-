data class CloudBuildResult(
    val repoOwner: String,
    val repoName: String,
    val repoUrl: String,
    val cloneUrl: String,
    val workflowRunId: Long?,
    val buildStatus: String,
    val actionsUrl: String,
    val artifactDownloadUrl: String?
)

class GitHubBuildRepository(
    private val customApi: GitHubApi? = null
) {

    private val json = Json {
        ignoreUnknownKeys = true
        isLenient = true
    }

    private val api: GitHubApi by lazy {
        customApi ?: run {
            val logging = HttpLoggingInterceptor().apply {
                level = HttpLoggingInterceptor.Level.BASIC
            }
            val client = OkHttpClient.Builder()
                .connectTimeout(30, TimeUnit.SECONDS)
                .readTimeout(60, TimeUnit.SECONDS)
                .writeTimeout(60, TimeUnit.SECONDS)
                .addInterceptor(logging)
                .build()

            Retrofit.Builder()
                .baseUrl("https://api.github.com/")
                .client(client)
                .addConverterFactory(json.asConverterFactory("application/json".toMediaType()))
                .build()
                .create(GitHubApi::class.java)
        }
    }

    suspend fun ensureGitHubRepo(
        pat: String,
        preferredUsername: String,
        preferredRepoName: String? = null
    ): Triple<String, String, String> = withContext(Dispatchers.IO) {
        val tokenHeader = formatAuthHeader(pat)
        val owner = preferredUsername.trim().ifBlank {
            api.getAuthenticatedUser(tokenHeader).login
        }
        val repoName = preferredRepoName?.trim()?.takeIf { it.isNotBlank() }
            ?: "ai-app-${System.currentTimeMillis() / 1000}"

        val created = api.createRepository(
            authorization = tokenHeader,
            request = CreateRepoRequest(
                name = repoName,
                description = "Android app generated by AI App Studio",
                isPrivate = false,
                autoInit = true
            )
        )
        Triple(owner, created.name, created.cloneUrl)
    }

    suspend fun pushProjectAndTriggerApkBuild(
        project: StudioProject,
        pat: String,
        preferredUsername: String,
        onProgress: suspend (String) -> Unit,
        onConsoleLog: (ConsoleLogEntry) -> Unit = {}
    ): CloudBuildResult = withContext(Dispatchers.IO) {
        val tokenHeader = formatAuthHeader(pat)
        onProgress("Authenticating with GitHub…")
        onConsoleLog(
            ConsoleLogEntry(
                id = UUID.randomUUID().toString(),
                level = ConsoleLogLevel.INFO,
                tag = "GitHubAuth",
                message = "Authenticating with api.github.com via Personal Access Token…"
            )
        )

        val owner = project.gitHubRepoOwner?.takeIf { it.isNotBlank() }
            ?: preferredUsername.trim().ifBlank {
                api.getAuthenticatedUser(tokenHeader).login
            }
        onConsoleLog(
            ConsoleLogEntry(
                id = UUID.randomUUID().toString(),
                level = ConsoleLogLevel.DEBUG,
                tag = "GitHubAuth",
                message = "Authenticated GitHub owner: @$owner"
            )
        )

        var repoName = project.gitHubRepoName?.takeIf { it.isNotBlank() }
        var repoUrl = project.gitHubRepoUrl
        var cloneUrl = if (repoName != null) "https://github.com/$owner/$repoName.git" else ""
        var defaultBranch = "main"

        if (repoName == null) {
            repoName = "ai-app-${System.currentTimeMillis() / 1000}"
            onProgress("Creating GitHub repository $owner/$repoName…")
            onConsoleLog(
                ConsoleLogEntry(
                    id = UUID.randomUUID().toString(),
                    level = ConsoleLogLevel.INFO,
                    tag = "GitHubRepo",
                    message = "POST /user/repos -> creating $owner/$repoName (branch: main)"
                )
            )
            val created = api.createRepository(
                authorization = tokenHeader,
                request = CreateRepoRequest(
                    name = repoName,
                    description = "Generated Android app: ${project.appName}",
                    isPrivate = false,
                    autoInit = true
                )
            )
            repoName = created.name
            repoUrl = created.htmlUrl
            cloneUrl = created.cloneUrl
            defaultBranch = created.defaultBranch.ifBlank { "main" }
            onConsoleLog(
                ConsoleLogEntry(
                    id = UUID.randomUUID().toString(),
                    level = ConsoleLogLevel.SUCCESS,
                    tag = "GitHubRepo",
                    message = "Created repository: $repoUrl"
                )
            )
        } else {
            repoUrl = repoUrl ?: "https://github.com/$owner/$repoName"
            onConsoleLog(
                ConsoleLogEntry(
                    id = UUID.randomUUID().toString(),
                    level = ConsoleLogLevel.INFO,
                    tag = "GitHubRepo",
                    message = "Reusing existing repository: $owner/$repoName"
                )
            )
        }

        val filesWithWorkflow = GitHubWorkflowInjector.injectBuildApkWorkflow(
            appName = project.appName,
            files = project.files
        )
        val normalizedFiles = filesWithWorkflow
            .mapNotNull { file ->
                val cleanPath = file.path.trim().removePrefix("/")
                if (cleanPath.isBlank() || cleanPath.contains("..")) null
                else file.copy(path = cleanPath)
            }
            .associateBy { it.path }
            .values
            .sortedBy { it.path }

        val previousLatestRunId = runCatching {
            api.listWorkflowRuns(tokenHeader, owner, repoName).workflowRuns.firstOrNull()?.id
        }.getOrNull()

        val pushedAtomically = runCatching {
            pushAtomicTreeCommit(
                tokenHeader = tokenHeader,
                owner = owner,
                repoName = repoName,
                branch = defaultBranch,
                appName = project.appName,
                files = normalizedFiles,
                onProgress = onProgress,
                onConsoleLog = onConsoleLog
            )
        }.onFailure { err ->
            onConsoleLog(
                ConsoleLogEntry(
                    id = UUID.randomUUID().toString(),
                    level = ConsoleLogLevel.WARN,
                    tag = "GitTreeSync",
                    message = "Atomic Git Data push unavailable (${err.localizedMessage}); falling back to Contents API…"
                )
            )
        }.isSuccess

        if (!pushedAtomically) {
            pushFilesIndividuallyFallback(
                tokenHeader = tokenHeader,
                owner = owner,
                repoName = repoName,
                branch = defaultBranch,
                files = normalizedFiles,
                onProgress = onProgress,
                onConsoleLog = onConsoleLog
            )
        }

        onProgress("Checking GitHub Actions workflow status…")
        onConsoleLog(
            ConsoleLogEntry(
                id = UUID.randomUUID().toString(),
                level = ConsoleLogLevel.INFO,
                tag = "GitHubActions",
                message = "Querying workflow runs for $owner/$repoName (.github/workflows/build-apk.yml)…"
            )
        )

        val latestRun = pollForNewWorkflowRun(
            tokenHeader = tokenHeader,
            owner = owner,
            repoName = repoName,
            previousRunId = previousLatestRunId
        )

        if (latestRun != null) {
            emitWorkflowJobSteps(tokenHeader, owner, repoName, latestRun.id, onConsoleLog)
        }
        val actionsUrl = latestRun?.htmlUrl ?: "$repoUrl/actions"
        val statusText = formatRunStatus(latestRun)
        val artifactUrl = if (latestRun != null && latestRun.conclusion == "success") {
            fetchArtifactUrl(tokenHeader, owner, repoName, latestRun.id)
        } else null

        onConsoleLog(
            ConsoleLogEntry(
                id = UUID.randomUUID().toString(),
                level = when (latestRun?.conclusion) {
                    "failure" -> ConsoleLogLevel.ERROR
                    "success" -> ConsoleLogLevel.SUCCESS
                    else -> ConsoleLogLevel.INFO
                },
                tag = "GitHubActions",
                message = "Workflow status: $statusText ($actionsUrl)"
            )
        )

        CloudBuildResult(
            repoOwner = owner,
            repoName = repoName,
            repoUrl = repoUrl,
            cloneUrl = cloneUrl,
            workflowRunId = latestRun?.id,
            buildStatus = statusText,
            actionsUrl = actionsUrl,
            artifactDownloadUrl = artifactUrl
        )
    }

    private suspend fun pushAtomicTreeCommit(
        tokenHeader: String,
        owner: String,
        repoName: String,
        branch: String,
        appName: String,
        files: List<GeneratedFile>,
        onProgress: suspend (String) -> Unit,
        onConsoleLog: (ConsoleLogEntry) -> Unit
    ) {
        val refPath = "heads/$branch"
        var headRef: com.example.data.remote.GitRefResponse? = null
        var lastError: Throwable? = null
        repeat(4) { attempt ->
            try {
                headRef = api.getGitRef(tokenHeader, owner, repoName, refPath)
                return@repeat
            } catch (ex: Throwable) {
                lastError = ex
                if (attempt < 3) delay(450L)
            }
        }
        val resolvedRef = headRef ?: throw (lastError ?: IllegalStateException("Unable to resolve $refPath"))
        val headCommitSha = resolvedRef.objectInfo.sha
        val baseTreeSha = api.getGitCommit(tokenHeader, owner, repoName, headCommitSha).tree.sha

        val treeEntries = mutableListOf<GitTreeEntry>()
        files.forEachIndexed { index, file ->
            onProgress("Uploading (${index + 1}/${files.size}): ${file.path}")
            val rawBytes = com.example.ui.assets.ProjectResAssetManager.decodeBinaryContent(file.content)
                ?: file.content.toByteArray(Charsets.UTF_8)
            val encodedBase64 = encodeBase64(rawBytes)
            val blob = api.createGitBlob(
                authorization = tokenHeader,
                owner = owner,
                repo = repoName,
                request = CreateGitBlobRequest(content = encodedBase64, encoding = "base64")
            )
            treeEntries += GitTreeEntry(
                path = file.path,
                mode = "100644",
                type = "blob",
                sha = blob.sha
            )
        }

        onProgress("Creating single atomic Git commit (${treeEntries.size} files)…")
        val newTree = api.createGitTree(
            authorization = tokenHeader,
            owner = owner,
            repo = repoName,
            request = CreateGitTreeRequest(
                baseTree = baseTreeSha,
                tree = treeEntries
            )
        )
        val newCommit = api.createGitCommit(
            authorization = tokenHeader,
            owner = owner,
            repo = repoName,
            request = CreateGitCommitRequest(
                message = "Sync $appName (${treeEntries.size} files) via AI App Studio",
                tree = newTree.sha,
                parents = listOf(headCommitSha)
            )
        )
        api.updateGitRef(
            authorization = tokenHeader,
            owner = owner,
            repo = repoName,
            ref = refPath,
            request = UpdateGitRefRequest(sha = newCommit.sha, force = false)
        )

        onConsoleLog(
            ConsoleLogEntry(
                id = UUID.randomUUID().toString(),
                level = ConsoleLogLevel.SUCCESS,
                tag = "GitTreeSync",
                message = "Committed ${treeEntries.size} files atomically in commit ${newCommit.sha.take(7)} on $branch"
            )
        )
    }

    private suspend fun pushFilesIndividuallyFallback(
        tokenHeader: String,
        owner: String,
        repoName: String,
        branch: String,
        files: List<GeneratedFile>,
        onProgress: suspend (String) -> Unit,
        onConsoleLog: (ConsoleLogEntry) -> Unit
    ) {
        files.forEachIndexed { index, file ->
            val cleanPath = file.path
            onProgress("Uploading (${index + 1}/${files.size}): $cleanPath")

            val existingSha = runCatching {
                api.getFileContent(
                    authorization = tokenHeader,
                    owner = owner,
                    repo = repoName,
                    path = cleanPath,
                    branch = branch
                ).sha
            }.getOrNull()

            val rawBytes = com.example.ui.assets.ProjectResAssetManager.decodeBinaryContent(file.content)
                ?: file.content.toByteArray(Charsets.UTF_8)
            val encodedContent = encodeBase64(rawBytes)

            api.putFileContent(
                authorization = tokenHeader,
                owner = owner,
                repo = repoName,
                path = cleanPath,
                request = PutContentRequest(
                    message = "Add/update $cleanPath via AI App Studio",
                    content = encodedContent,
                    branch = branch,
                    sha = existingSha
                )
            )

            onConsoleLog(
                ConsoleLogEntry(
                    id = UUID.randomUUID().toString(),
                    level = ConsoleLogLevel.DEBUG,
                    tag = "GitTreeSync",
                    message = "[${index + 1}/${files.size}] Committed $cleanPath (${rawBytes.size} bytes)",
                    filePath = cleanPath
                )
            )
        }
    }

    private suspend fun pollForNewWorkflowRun(
        tokenHeader: String,
        owner: String,
        repoName: String,
        previousRunId: Long?
    ): WorkflowRun? {
        var latestRun: WorkflowRun? = null
        repeat(3) { attempt ->
            val runs = runCatching {
                api.listWorkflowRuns(tokenHeader, owner, repoName).workflowRuns
            }.getOrDefault(emptyList())
            latestRun = runs.firstOrNull()
            if (latestRun != null && (previousRunId == null || latestRun!!.id != previousRunId)) {
                return latestRun
            }
            if (attempt < 2) delay(1200L)
        }
        return latestRun
    }

    suspend fun refreshBuildStatus(
        project: StudioProject,
        pat: String,
        onConsoleLog: (ConsoleLogEntry) -> Unit = {}
    ): CloudBuildResult = withContext(Dispatchers.IO) {
        val owner = project.gitHubRepoOwner
            ?: throw IllegalStateException("No GitHub repository linked to this project yet.")
        val repoName = project.gitHubRepoName
            ?: throw IllegalStateException("No GitHub repository name linked to this project yet.")
        val repoUrl = project.gitHubRepoUrl ?: "https://github.com/$owner/$repoName"
        val tokenHeader = formatAuthHeader(pat)

        onConsoleLog(
            ConsoleLogEntry(
                id = UUID.randomUUID().toString(),
                level = ConsoleLogLevel.INFO,
                tag = "GitHubActions",
                message = "Polling GitHub Actions runs for $owner/$repoName…"
            )
        )

        val runs = api.listWorkflowRuns(tokenHeader, owner, repoName).workflowRuns
        val latestRun = runs.firstOrNull()
        if (latestRun != null) {
            emitWorkflowJobSteps(tokenHeader, owner, repoName, latestRun.id, onConsoleLog)
        }
        val artifactUrl = if (latestRun != null && latestRun.conclusion == "success") {
            fetchArtifactUrl(tokenHeader, owner, repoName, latestRun.id)
        } else null

        val statusText = formatRunStatus(latestRun)
        onConsoleLog(
            ConsoleLogEntry(
                id = UUID.randomUUID().toString(),
                level = when (latestRun?.conclusion) {
                    "failure" -> ConsoleLogLevel.ERROR
                    "success" -> ConsoleLogLevel.SUCCESS
                    else -> ConsoleLogLevel.INFO
                },
                tag = "GitHubActions",
                message = "Run #${latestRun?.id ?: "pending"}: $statusText"
            )
        )

        CloudBuildResult(
            repoOwner = owner,
            repoName = repoName,
            repoUrl = repoUrl,
            cloneUrl = "https://github.com/$owner/$repoName.git",
            workflowRunId = latestRun?.id,
            buildStatus = statusText,
            actionsUrl = latestRun?.htmlUrl ?: "$repoUrl/actions",
            artifactDownloadUrl = artifactUrl
        )
    }

    private suspend fun emitWorkflowJobSteps(
        tokenHeader: String,
        owner: String,
        repoName: String,
        runId: Long,
        onConsoleLog: (ConsoleLogEntry) -> Unit
    ) {
        runCatching {
            val jobs = api.listWorkflowRunJobs(tokenHeader, owner, repoName, runId).jobs
            for (job in jobs) {
                for (step in job.steps) {
                    val level = when (step.conclusion) {
                        "failure" -> ConsoleLogLevel.ERROR
                        "success" -> ConsoleLogLevel.SUCCESS
                        "skipped" -> ConsoleLogLevel.DEBUG
                        else -> if (step.status == "in_progress") ConsoleLogLevel.INFO else ConsoleLogLevel.DEBUG
                    }
                    val detail = step.conclusion ?: step.status
                    onConsoleLog(
                        ConsoleLogEntry(
                            id = UUID.randomUUID().toString(),
                            level = level,
                            tag = "GradleStep#${step.number}",
                            message = "[${job.name}] ${step.name} -> $detail" +
                                if (step.conclusion == "failure") " (Compiler/Gradle step failed — run static check or inspect Actions log)" else ""
                        )
                    )
                }
            }
        }
    }

    private suspend fun fetchArtifactUrl(
        tokenHeader: String,
        owner: String,
        repoName: String,
        runId: Long
    ): String? {
        return runCatching {
            val artifacts = api.listRunArtifacts(tokenHeader, owner, repoName, runId).artifacts
            artifacts.firstOrNull { !it.expired }?.let {
                "https://github.com/$owner/$repoName/actions/runs/$runId"
            }
        }.getOrNull()
    }

    suspend fun downloadCompiledApkArtifact(
        pat: String,
        owner: String,
        repoName: String,
        runId: Long,
        targetDownloadsDir: File,
        appName: String,
        onProgress: suspend (String) -> Unit = {}
    ): File? = withContext(Dispatchers.IO) {
        val tokenHeader = formatAuthHeader(pat)
        val artifacts = runCatching {
            api.listRunArtifacts(tokenHeader, owner, repoName, runId).artifacts
        }.getOrDefault(emptyList())

        val activeArtifact = artifacts.firstOrNull { !it.expired } ?: return@withContext null
        onProgress("Downloading artifact '${activeArtifact.name}' (${activeArtifact.sizeInBytes / 1024} KB)…")

        targetDownloadsDir.mkdirs()
        val safeAppName = appName.lowercase()
            .replace(Regex("[^a-z0-9]+"), "-")
            .trim('-')
            .ifBlank { "app" }
        val outputApkFile = File(targetDownloadsDir, "$safeAppName-debug.apk")

        val responseBody = api.downloadArtifactZip(
            authorization = tokenHeader,
            owner = owner,
            repo = repoName,
            artifactId = activeArtifact.id
        )

        var extractedApk = false
        responseBody.byteStream().use { rawStream ->
            ZipInputStream(rawStream).use { zis ->
                var entry = zis.nextEntry
                while (entry != null) {
                    if (!entry.isDirectory && entry.name.endsWith(".apk", ignoreCase = true)) {
                        FileOutputStream(outputApkFile).use { fos ->
                            zis.copyTo(fos, bufferSize = 64 * 1024)
                        }
                        extractedApk = true
                        zis.closeEntry()
                        break
                    }
                    zis.closeEntry()
                    entry = zis.nextEntry
                }
            }
        }

        if (extractedApk && outputApkFile.exists() && outputApkFile.length() > 0L) {
            outputApkFile
        } else {
            null
        }
    }

    private fun formatRunStatus(run: WorkflowRun?): String {
        if (run == null) return "Queued — check GitHub Actions"
        return when (run.status) {
            "completed" -> when (run.conclusion) {
                "success" -> "Build Succeeded (Debug APK Ready)"
                "failure" -> "Build Failed — inspect Actions log"
                else -> "Completed (${run.conclusion ?: "unknown"})"
            }
            "in_progress" -> "Building Debug APK on GitHub Actions…"
            "queued" -> "Queued on GitHub Actions runner…"
            else -> run.status.replaceFirstChar { it.uppercase() }
        }
    }

    private fun formatAuthHeader(pat: String): String {
        val clean = pat.trim()
        if (clean.isBlank()) {
            throw IllegalArgumentException(
                "GitHub Personal Access Token (PAT) is missing. Configure it in Settings."
            )
        }
        return "Bearer $clean"
    }

    fun buildErrorMessage(error: Throwable): String {
        return if (error is HttpException) {
            val detail = runCatching { error.response()?.errorBody()?.string() }.getOrNull()
            when (error.code()) {
                401 -> "GitHub rejected your PAT (401 Unauthorized)."
                403 -> "GitHub permission denied (403). Ensure your PAT has 'repo' and 'workflow' scopes."
                422 -> "GitHub validation error (422): ${detail ?: "Repository name may already exist."}"
                else -> "GitHub HTTP ${error.code()}: ${detail ?: error.message()}"
            }
        } else {
            error.localizedMessage ?: "GitHub operation failed."
        }
    }

    private fun encodeBase64(bytes: ByteArray): String {
        if (bytes.isEmpty()) return ""
        val alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
        val sb = StringBuilder(((bytes.size + 2) / 3) * 4)
        var i = 0
        while (i < bytes.size) {
            val b0 = bytes[i].toInt() and 0xFF
            val hasB1 = i + 1 < bytes.size
            val hasB2 = i + 2 < bytes.size
            val b1 = if (hasB1) bytes[i + 1].toInt() and 0xFF else 0
            val b2 = if (hasB2) bytes[i + 2].toInt() and 0xFF else 0
            sb.append(alphabet[b0 ushr 2])
            sb.append(alphabet[((b0 and 0x03) shl 4) or (b1 ushr 4)])
            sb.append(if (hasB1) alphabet[((b1 and 0x0F) shl 2) or (b2 ushr 6)] else '=')
            sb.append(if (hasB2) alphabet[b2 and 0x3F] else '=')
            i += 3
        }
        return sb.toString()
    }

    companion object {
        fun buildApkWorkflowYaml(appName: String): String =
            GitHubWorkflowInjector.generateBuildApkWorkflowYaml(appName)
    }
