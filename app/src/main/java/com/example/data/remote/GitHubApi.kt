package com.example.data.remote

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import okhttp3.ResponseBody
import retrofit2.http.Body
import retrofit2.http.GET
import retrofit2.http.Header
import retrofit2.http.POST
import retrofit2.http.PUT
import retrofit2.http.Path
import retrofit2.http.Query
import retrofit2.http.Streaming

@Serializable
data class GitHubUserResponse(
    val login: String,
    val name: String? = null
)

@Serializable
data class CreateRepoRequest(
    val name: String,
    val description: String = "Generated by AI App Studio",
    @SerialName("private")
    val isPrivate: Boolean = false,
    @SerialName("auto_init")
    val autoInit: Boolean = true
)

@Serializable
data class GitHubRepoResponse(
    val id: Long,
    val name: String,
    @SerialName("full_name")
    val fullName: String,
    @SerialName("html_url")
    val htmlUrl: String,
    @SerialName("clone_url")
    val cloneUrl: String,
    @SerialName("default_branch")
    val defaultBranch: String = "main"
)

@Serializable
data class GitHubContentGetResponse(
    val sha: String,
    val path: String
)

@Serializable
data class PutContentRequest(
    val message: String,
    val content: String,
    val branch: String = "main",
    val sha: String? = null
)

@Serializable
data class PutContentResponse(
    val content: GitHubContentFileInfo? = null
)

@Serializable
data class GitHubContentFileInfo(
    val path: String? = null,
    val sha: String? = null
)

@Serializable
data class WorkflowRunsResponse(
    @SerialName("total_count")
    val totalCount: Int = 0,
    @SerialName("workflow_runs")
    val workflowRuns: List<WorkflowRun> = emptyList()
)

@Serializable
data class WorkflowRun(
    val id: Long,
    val name: String? = null,
    val status: String,
    val conclusion: String? = null,
    @SerialName("html_url")
    val htmlUrl: String,
    @SerialName("created_at")
    val createdAt: String? = null
)

@Serializable
data class ArtifactsResponse(
    @SerialName("total_count")
    val totalCount: Int = 0,
    val artifacts: List<GitHubArtifact> = emptyList()
)

@Serializable
data class GitHubArtifact(
    val id: Long,
    val name: String,
    @SerialName("size_in_bytes")
    val sizeInBytes: Long = 0L,
    @SerialName("archive_download_url")
    val archiveDownloadUrl: String,
    val expired: Boolean = false
)

@Serializable
data class WorkflowJobsResponse(
    @SerialName("total_count")
    val totalCount: Int = 0,
    val jobs: List<WorkflowJob> = emptyList()
)

@Serializable
data class WorkflowJob(
    val id: Long,
    val name: String,
    val status: String,
    val conclusion: String? = null,
    @SerialName("html_url")
    val htmlUrl: String? = null,
    val steps: List<WorkflowStep> = emptyList()
)

@Serializable
data class WorkflowStep(
    val name: String,
    val status: String,
    val conclusion: String? = null,
    val number: Int = 0
)

@Serializable
data class GitRefObject(
    val sha: String,
    val type: String? = null
)

@Serializable
data class GitRefResponse(
    val ref: String,
    @SerialName("object")
    val objectInfo: GitRefObject
)

@Serializable
data class GitTreeRef(
    val sha: String
)

@Serializable
data class GitCommitResponse(
    val sha: String,
    val tree: GitTreeRef
)

@Serializable
data class CreateGitBlobRequest(
    val content: String,
    val encoding: String = "base64"
)

@Serializable
data class CreateGitBlobResponse(
    val sha: String
)

@Serializable
data class GitTreeEntry(
    val path: String,
    val mode: String = "100644",
    val type: String = "blob",
    val sha: String
)

@Serializable
data class CreateGitTreeRequest(
    @SerialName("base_tree")
    val baseTree: String? = null,
    val tree: List<GitTreeEntry>
)

@Serializable
data class CreateGitTreeResponse(
    val sha: String
)

@Serializable
data class CreateGitCommitRequest(
    val message: String,
    val tree: String,
    val parents: List<String> = emptyList()
)

@Serializable
data class CreateGitCommitResponse(
    val sha: String
)

@Serializable
data class UpdateGitRefRequest(
    val sha: String,
    val force: Boolean = false
)

interface GitHubApi {
    @GET("user")
    suspend fun getAuthenticatedUser(
        @Header("Authorization") authorization: String,
        @Header("Accept") accept: String = "application/vnd.github+json"
    ): GitHubUserResponse

    @POST("user/repos")
    suspend fun createRepository(
        @Header("Authorization") authorization: String,
        @Header("Accept") accept: String = "application/vnd.github+json",
        @Body request: CreateRepoRequest
    ): GitHubRepoResponse

    @GET("repos/{owner}/{repo}/git/ref/{ref}")
    suspend fun getGitRef(
        @Header("Authorization") authorization: String,
        @Path("owner") owner: String,
        @Path("repo") repo: String,
        @Path("ref", encoded = true) ref: String = "heads/main",
        @Header("Accept") accept: String = "application/vnd.github+json"
    ): GitRefResponse

    @GET("repos/{owner}/{repo}/git/commits/{commit_sha}")
    suspend fun getGitCommit(
        @Header("Authorization") authorization: String,
        @Path("owner") owner: String,
        @Path("repo") repo: String,
        @Path("commit_sha") commitSha: String,
        @Header("Accept") accept: String = "application/vnd.github+json"
    ): GitCommitResponse

    @POST("repos/{owner}/{repo}/git/blobs")
    suspend fun createGitBlob(
        @Header("Authorization") authorization: String,
        @Path("owner") owner: String,
        @Path("repo") repo: String,
        @Body request: CreateGitBlobRequest,
        @Header("Accept") accept: String = "application/vnd.github+json"
    ): CreateGitBlobResponse

    @POST("repos/{owner}/{repo}/git/trees")
    suspend fun createGitTree(
        @Header("Authorization") authorization: String,
        @Path("owner") owner: String,
        @Path("repo") repo: String,
        @Body request: CreateGitTreeRequest,
        @Header("Accept") accept: String = "application/vnd.github+json"
    ): CreateGitTreeResponse

    @POST("repos/{owner}/{repo}/git/commits")
    suspend fun createGitCommit(
        @Header("Authorization") authorization: String,
        @Path("owner") owner: String,
        @Path("repo") repo: String,
        @Body request: CreateGitCommitRequest,
        @Header("Accept") accept: String = "application/vnd.github+json"
    ): CreateGitCommitResponse

    @retrofit2.http.PATCH("repos/{owner}/{repo}/git/refs/{ref}")
    suspend fun updateGitRef(
        @Header("Authorization") authorization: String,
        @Path("owner") owner: String,
        @Path("repo") repo: String,
        @Path("ref", encoded = true) ref: String = "heads/main",
        @Body request: UpdateGitRefRequest,
        @Header("Accept") accept: String = "application/vnd.github+json"
    ): GitRefResponse

    @GET("repos/{owner}/{repo}/contents/{path}")
    suspend fun getFileContent(
        @Header("Authorization") authorization: String,
        @Path("owner") owner: String,
        @Path("repo") repo: String,
        @Path("path", encoded = true) path: String,
        @Query("ref") branch: String = "main",
        @Header("Accept") accept: String = "application/vnd.github+json"
    ): GitHubContentGetResponse

    @PUT("repos/{owner}/{repo}/contents/{path}")
    suspend fun putFileContent(
        @Header("Authorization") authorization: String,
        @Path("owner") owner: String,
        @Path("repo") repo: String,
        @Path("path", encoded = true) path: String,
        @Body request: PutContentRequest,
        @Header("Accept") accept: String = "application/vnd.github+json"
    ): PutContentResponse

    @GET("repos/{owner}/{repo}/actions/runs")
    suspend fun listWorkflowRuns(
        @Header("Authorization") authorization: String,
        @Path("owner") owner: String,
        @Path("repo") repo: String,
        @Query("per_page") perPage: Int = 5,
        @Header("Accept") accept: String = "application/vnd.github+json"
    ): WorkflowRunsResponse

    @GET("repos/{owner}/{repo}/actions/runs/{run_id}/artifacts")
    suspend fun listRunArtifacts(
        @Header("Authorization") authorization: String,
        @Path("owner") owner: String,
        @Path("repo") repo: String,
        @Path("run_id") runId: Long,
        @Header("Accept") accept: String = "application/vnd.github+json"
    ): ArtifactsResponse

    @GET("repos/{owner}/{repo}/actions/runs/{run_id}/jobs")
    suspend fun listWorkflowRunJobs(
        @Header("Authorization") authorization: String,
        @Path("owner") owner: String,
        @Path("repo") repo: String,
        @Path("run_id") runId: Long,
        @Header("Accept") accept: String = "application/vnd.github+json"
    ): WorkflowJobsResponse

    @Streaming
    @GET("repos/{owner}/{repo}/actions/artifacts/{artifact_id}/zip")
    suspend fun downloadArtifactZip(
        @Header("Authorization") authorization: String,
        @Path("owner") owner: String,
        @Path("repo") repo: String,
        @Path("artifact_id") artifactId: Long,
        @Header("Accept") accept: String = "application/vnd.github+json"
    ): ResponseBody
}

